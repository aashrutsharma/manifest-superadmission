/**
 * Expands a raw search string into multiple matching terms.
 * Handles acronyms, short forms, and city variants without ever searching AISHE codes.
 */
export function expandSearchQuery(query: string): string[] {
  const trimmed = query.trim();
  if (!trimmed) return [];

  const cleanKey = trimmed.toLowerCase().replace(/[^a-z0-9]/g, '');
  const expansions = new Set<string>();
  expansions.add(trimmed);

  // Exact acronym match
  if (COLLEGE_ACRONYMS[cleanKey]) {
    COLLEGE_ACRONYMS[cleanKey].forEach((term) => expansions.add(term));
  }

  // Check prefix / partial match for acronyms (e.g. "iit" matches "Indian Institute of Technology")
  for (const [acronym, terms] of Object.entries(COLLEGE_ACRONYMS)) {
    if (cleanKey === acronym || (cleanKey.length >= 4 && cleanKey.startsWith(acronym))) {
      terms.forEach((term) => expansions.add(term));
    }
  }

  // City alias expansion
  for (const [alias, targets] of Object.entries(CITY_ALIASES)) {
    if (cleanKey === alias || trimmed.toLowerCase().includes(alias)) {
      targets.forEach((target) => expansions.add(target));
    }
  }

  return Array.from(expansions);
}

/**
 * Fuzzy matches an institution against a search query using name, city, state, and discipline.
 * Strictly ignores AISHE codes to prevent false matches.
 */
export function fuzzyMatchInstitution(
  institution: {
    name: string;
    shortName?: string;
    city?: string;
    state?: string;
    streams?: string[];
  },
  query: string
): boolean {
  if (!query || !query.trim()) return true;

  const raw = query.trim().toLowerCase();
  const searchTokens = raw.split(/\s+/).filter((t) => t.length > 0);
  if (searchTokens.length === 0) return true;

  const instName = (institution.name || '').toLowerCase();
  const instShort = (institution.shortName || '').toLowerCase();
  const instCity = (institution.city || '').toLowerCase();
  const instState = (institution.state || '').toLowerCase();
  const instStreams = (institution.streams || []).map((s) => s.toLowerCase()).join(' ');

  const fullSearchable = `${instName} ${instShort} ${instCity} ${instState} ${instStreams}`;

  // 1. Direct substring match
  if (fullSearchable.includes(raw)) return true;

  // 2. Acronym expansion match
  const expanded = expandSearchQuery(query);
  for (const term of expanded) {
    if (fullSearchable.includes(term.toLowerCase())) {
      return true;
    }
  }

  // 3. Multi-token match (all query tokens must appear in searchable fields)
  const allTokensMatch = searchTokens.every((token) => fullSearchable.includes(token));
  if (allTokensMatch) return true;

  // 4. Token prefix match (e.g. "thap" matches "Thapar", "bomb" matches "Bombay")
  if (searchTokens.length > 0 && searchTokens.every((token) => token.length >= 3)) {
    const allPrefixesMatch = searchTokens.every((token) => {
      const words = fullSearchable.split(/[\s,.-]+/);
      return words.some((w) => w.startsWith(token));
    });
    if (allPrefixesMatch) return true;
  }

  return false;
}
